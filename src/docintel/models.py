"""Data models.

Two families live here:

* **Pipeline records** (documents, pages, chunks, source passages) created by the application.
* **LLM output schemas** (``QAOutput``, ``SummaryOutput``, ...) that the model must return.
  These are sent to providers as strict JSON schemas, so every field is required and has no
  default (OpenAI strict mode requires this; optional values are expressed as ``X | None``).

Source identifiers (``S1``, ``S2``...) are generated by the application for each request.
The model may only reference identifiers that were present in its context; the grounding
module rejects anything else.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

# --------------------------------------------------------------------------- pipeline records


class PageText(BaseModel):
    page_number: int  # 1-based, as displayed in PDF viewers
    text: str
    has_images: bool = False


class DocumentRecord(BaseModel):
    doc_id: str
    filename: str
    sha256: str
    size_bytes: int
    page_count: int
    pages: list[PageText]
    metadata: dict[str, str] = Field(default_factory=dict)
    warnings: list[str] = Field(default_factory=list)
    notes: list[str] = Field(default_factory=list)  # informational (e.g. boilerplate removal)
    empty_pages: list[int] = Field(default_factory=list)

    @property
    def char_count(self) -> int:
        return sum(len(p.text) for p in self.pages)

    def page(self, page_number: int) -> PageText | None:
        if 1 <= page_number <= len(self.pages):
            return self.pages[page_number - 1]
        return None


class Chunk(BaseModel):
    chunk_id: str  # "<doc_id>:p<page>:c<index>", deterministic
    doc_id: str
    filename: str
    page_number: int
    chunk_index: int  # index within the page
    ordinal: int  # position within the whole document (stable tie-breaker)
    text: str  # exact substring of the normalized page text
    char_start: int
    char_end: int
    flags: list[str] = Field(default_factory=list)
    # Document-level context (title / file name) added to the *search index only*, so each chunk
    # stays findable by document name without repeating boilerplate in passages shown to the model.
    context_header: str = ""

    @property
    def index_text(self) -> str:
        return f"{self.context_header}\n{self.text}" if self.context_header else self.text


class SourcePassage(BaseModel):
    """A chunk as shown to the model for one request, under a request-scoped source ID."""

    source_id: str  # "S1", "S2", ...
    chunk_id: str
    doc_id: str
    filename: str
    page_number: int
    text: str
    score: float | None = None
    flags: list[str] = Field(default_factory=list)


# --------------------------------------------------------------------------- LLM output schemas

_STRICT = ConfigDict(extra="forbid")


class Citation(BaseModel):
    model_config = _STRICT
    source_id: str = Field(
        description="ID of one of the provided sources, e.g. 'S2'. Never invent an ID."
    )
    quote: str = Field(
        description="A short excerpt (at most about 30 words) copied verbatim from that source "
        "which supports the statement."
    )


class Claim(BaseModel):
    model_config = _STRICT
    statement: str = Field(description="One self-contained statement made in the answer.")
    claim_type: Literal["fact", "inference"] = Field(
        description="'fact' if the sources state it directly; 'inference' if it is your "
        "reasoning from the sources."
    )
    citations: list[Citation]


class ConflictNote(BaseModel):
    model_config = _STRICT
    description: str
    nature: Literal["direct_contradiction", "context_difference", "unclear"]
    source_ids: list[str]


class QAOutput(BaseModel):
    model_config = _STRICT
    status: Literal[
        "answered", "partially_answered", "insufficient_evidence", "conflicting_evidence"
    ]
    answer: str = Field(
        description="The answer for the user, citing sources inline like [S1]. If the sources do "
        "not contain the answer, say so plainly."
    )
    claims: list[Claim]
    conflicts: list[ConflictNote]
    missing_information: list[str] = Field(
        description="Parts of the question the sources do not answer."
    )
    confidence: Literal["high", "medium", "low"]


class SummaryPoint(BaseModel):
    model_config = _STRICT
    text: str
    source_ids: list[str]


class DatedItem(BaseModel):
    model_config = _STRICT
    date: str = Field(description="The date exactly as written in the source.")
    description: str
    source_ids: list[str]


class SectionNotes(BaseModel):
    """Map-step output for one section of a long document."""

    model_config = _STRICT
    section_summary: str = Field(description="Summary of this section with inline [S#] citations.")
    key_points: list[SummaryPoint]
    dates: list[DatedItem]
    action_items: list[SummaryPoint]
    obligations: list[SummaryPoint]
    risks: list[SummaryPoint]


class SummaryOutput(BaseModel):
    model_config = _STRICT
    executive_summary: str = Field(description="3-5 sentences with inline [S#] citations.")
    detailed_summary: str = Field(description="Several paragraphs with inline [S#] citations.")
    key_findings: list[SummaryPoint]
    important_dates: list[DatedItem]
    action_items: list[SummaryPoint]
    obligations: list[SummaryPoint]
    risks_and_concerns: list[SummaryPoint]
    gaps_or_limitations: list[str] = Field(
        description="Anything that could not be summarized reliably (e.g. missing or unclear content)."
    )


class ExtractedItem(BaseModel):
    model_config = _STRICT
    value: str = Field(description="The extracted value exactly as written in the source.")
    normalized_value: str | None = Field(
        description="Normalized form when applicable (dates as YYYY-MM-DD, money as "
        "'USD 1234.56'); null if not applicable or not determinable."
    )
    detail: str | None = Field(
        description="Role, purpose or context stated in the source; null if the source does not say."
    )
    source_id: str
    quote: str = Field(description="Short verbatim excerpt from the source containing the value.")


class ExtractionOutput(BaseModel):
    model_config = _STRICT
    people: list[ExtractedItem]
    organizations: list[ExtractedItem]
    dates: list[ExtractedItem]
    monetary_amounts: list[ExtractedItem]
    responsibilities: list[ExtractedItem]
    obligations: list[ExtractedItem]
    decisions: list[ExtractedItem]
    risks: list[ExtractedItem]
    key_facts: list[ExtractedItem]
    not_found: list[str] = Field(description="Categories for which the sources contain nothing.")


EXTRACTION_CATEGORIES: tuple[str, ...] = (
    "people",
    "organizations",
    "dates",
    "monetary_amounts",
    "responsibilities",
    "obligations",
    "decisions",
    "risks",
    "key_facts",
)


class ComparisonFinding(BaseModel):
    model_config = _STRICT
    category: Literal[
        "similarity",
        "difference",
        "conflict",
        "numerical_discrepancy",
        "obligation_or_deadline_difference",
        "missing_information",
        "important_change",
    ]
    topic: str
    description: str = Field(description="What differs or agrees, with inline [S#] citations.")
    nature: Literal["direct_contradiction", "context_difference", "not_a_conflict", "unclear"] = (
        Field(
            description="For conflicts and discrepancies: is it a genuine contradiction about the same "
            "thing, or explained by different context (dates, versions, scope)?"
        )
    )
    source_ids: list[str]


class ComparisonOutput(BaseModel):
    model_config = _STRICT
    overview: str
    findings: list[ComparisonFinding]
    limitations: str


class JudgeVerdict(BaseModel):
    """Optional LLM-as-judge rating of whether a cited quote supports a statement (evaluation only)."""

    model_config = _STRICT
    verdict: Literal["supported", "partially_supported", "not_supported"]
    rationale: str
