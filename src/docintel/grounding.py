"""Citation validation and evidence-support checks.

Three separate questions are answered for every citation, and they are reported separately
because a "yes" to the first does not imply the others:

1. **Does the source ID exist?** IDs are generated by the application per request; anything
   else (e.g. ``S99`` requested by an injected instruction) is flagged as fabricated.
2. **Is the quoted text really in that source?** Exact match after normalization, or an
   approximate word-level match (>= 0.85 similarity); otherwise ``not_found``.
3. **Does the cited passage plausibly support the statement?** A *heuristic* lexical check:
   the share of the statement's content words found in the cited passages, with a penalty when
   the statement contains numbers that do not appear in them. This is a screening signal, not a
   semantic verification; the evaluation suite adds an optional LLM-judge and human review.

The UI never calls an answer "verified"; it reports these signals and asks for human review.
"""

from __future__ import annotations

import re
import unicodedata
from collections.abc import Iterable, Sequence
from difflib import SequenceMatcher
from typing import Literal

from pydantic import BaseModel, Field

from docintel.models import (
    ComparisonOutput,
    ExtractionOutput,
    QAOutput,
    SourcePassage,
    SummaryOutput,
)
from docintel.prompting import PROMPT_CANARY
from docintel.retrieval import tokenize

QuoteStatus = Literal["exact", "approximate", "not_found", "missing", "not_applicable"]
SupportLabel = Literal["likely_supported", "weak", "unsupported", "not_assessed"]
Verdict = Literal["grounded", "review", "unsupported", "abstained"]

_INLINE_REF = re.compile(r"\[\s*(S\d+(?:\s*[,;]\s*S\d+)*)\s*\]")
_SOURCE_ID = re.compile(r"S\d+")
_NUMBER = re.compile(r"(?<![A-Za-z])\d[\d,]*(?:\.\d+)?")

APPROXIMATE_THRESHOLD = 0.85
LIKELY_SUPPORTED = 0.6
WEAK_SUPPORT = 0.35
CROSS_DOCUMENT_CATEGORIES = {
    "similarity",
    "difference",
    "conflict",
    "numerical_discrepancy",
    "obligation_or_deadline_difference",
    "important_change",
}


class CitationCheck(BaseModel):
    ref: str  # where the citation came from, e.g. "claims[0].citations[1]" or "people[2]"
    source_id: str
    known: bool
    doc_id: str | None = None
    filename: str | None = None
    page_number: int | None = None
    statement: str | None = None
    quote: str | None = None
    quote_status: QuoteStatus = "not_applicable"
    quote_similarity: float | None = None
    support_score: float | None = None
    support_label: SupportLabel = "not_assessed"
    notes: list[str] = Field(default_factory=list)


class GroundingReport(BaseModel):
    checks: list[CitationCheck] = Field(default_factory=list)
    unknown_source_ids: list[str] = Field(default_factory=list)
    unsupported_numbers: list[str] = Field(default_factory=list)
    uncited_items: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)
    canary_leak: bool = False
    abstained: bool = False

    @property
    def total_citations(self) -> int:
        return len(self.checks)

    @property
    def valid_citations(self) -> int:
        return sum(1 for c in self.checks if c.known)

    @property
    def quotes_checked(self) -> int:
        return sum(
            1
            for c in self.checks
            if c.quote_status in {"exact", "approximate", "not_found", "missing"}
        )

    @property
    def quotes_found(self) -> int:
        return sum(1 for c in self.checks if c.quote_status in {"exact", "approximate"})

    @property
    def likely_supported(self) -> int:
        return sum(1 for c in self.checks if c.support_label == "likely_supported")

    @property
    def assessed(self) -> int:
        return sum(1 for c in self.checks if c.support_label != "not_assessed")

    @property
    def verdict(self) -> Verdict:
        if self.canary_leak or self.unknown_source_ids:
            return "unsupported"
        if self.abstained and not self.checks:
            return "abstained"
        if not self.checks or self.valid_citations == 0:
            return "unsupported"
        problems = (
            any(c.quote_status in {"not_found", "missing"} for c in self.checks)
            or any(c.support_label == "unsupported" for c in self.checks)
            or bool(self.unsupported_numbers)
            or bool(self.uncited_items)
        )
        return "review" if problems else "grounded"

    def summary_line(self) -> str:
        if self.verdict == "abstained":
            return "No answer given (insufficient evidence), so there are no citations to check."
        parts = [
            f"{self.valid_citations}/{self.total_citations} citations point to provided sources"
        ]
        if self.quotes_checked:
            parts.append(
                f"{self.quotes_found}/{self.quotes_checked} quotes found in the cited source"
            )
        if self.assessed:
            parts.append(
                f"{self.likely_supported}/{self.assessed} pass the heuristic support check"
            )
        return "; ".join(parts) + "."


# --------------------------------------------------------------------------- primitives


def normalize_for_match(text: str) -> str:
    text = unicodedata.normalize("NFKC", text or "").lower()
    replacements = {
        "“": '"',
        "”": '"',
        "„": '"',
        "‘": "'",
        "’": "'",
        "‚": "'",
        "–": "-",
        "—": "-",
        "‐": "-",
        "‑": "-",
        "…": "...",
        "‹": "<",
        "›": ">",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    # Hyphen-insensitive between letters: "cross-sectional" == "crosssectional", "go-live" == "golive"
    # (PDF line-break hyphenation is ambiguous, so quotes must not fail on it).
    text = re.sub(r"(?<=[a-z])-\s?(?=[a-z])", "", text)
    return re.sub(r"\s+", " ", text).strip()


def extract_inline_ids(text: str) -> list[str]:
    ids: list[str] = []
    for match in _INLINE_REF.finditer(text or ""):
        ids.extend(_SOURCE_ID.findall(match.group(1)))
    return ids


def match_quote(quote: str, source_text: str) -> tuple[QuoteStatus, float]:
    """Check whether ``quote`` appears in ``source_text`` (exactly or approximately)."""
    q = normalize_for_match(quote).strip(" \"'.,;:")
    if len(q) < 3:
        return "missing", 0.0
    t = normalize_for_match(source_text)
    if q in t:
        return "exact", 1.0
    parts = [p.strip(" \"'.,;:") for p in re.split(r"\.\.\.|\[\.\.\.\]", q) if p.strip(" \"'.,;:")]
    if len(parts) > 1 and all(p in t for p in parts):
        return "approximate", 0.95
    q_words, t_words = q.split(), t.split()
    if not t_words:
        return "not_found", 0.0
    width = len(q_words)
    best = 0.0
    for start in range(0, max(1, len(t_words) - width + 1)):
        ratio = SequenceMatcher(
            None, q_words, t_words[start : start + width], autojunk=False
        ).ratio()
        if ratio > best:
            best = ratio
            if best >= 0.999:
                break
    if best >= APPROXIMATE_THRESHOLD:
        return "approximate", round(best, 3)
    return "not_found", round(best, 3)


def _numbers(text: str) -> set[str]:
    found = set()
    for raw in _NUMBER.findall(_INLINE_REF.sub(" ", text or "")):
        value = raw.replace(",", "")
        if "." in value:
            value = value.rstrip("0").rstrip(".")
        if value:
            found.add(value)
    return found


def support_score(
    statement: str, evidence: Iterable[str], *, inference: bool = False
) -> tuple[float, list[str]]:
    """Heuristic support of ``statement`` by ``evidence`` texts. Returns (score, missing_numbers)."""
    evidence_text = " ".join(evidence)
    statement_clean = _INLINE_REF.sub(" ", statement or "")
    s_terms = set(tokenize(statement_clean))
    e_terms = set(tokenize(evidence_text))
    score = 1.0 if not s_terms else len(s_terms & e_terms) / len(s_terms)
    missing_numbers = sorted(_numbers(statement_clean) - _numbers(evidence_text))
    if missing_numbers and not inference:
        score *= 0.5
    return round(score, 3), missing_numbers


def _label(score: float) -> SupportLabel:
    if score >= LIKELY_SUPPORTED:
        return "likely_supported"
    if score >= WEAK_SUPPORT:
        return "weak"
    return "unsupported"


def _check(
    ref: str,
    source_id: str,
    passages: dict[str, SourcePassage],
    *,
    statement: str | None = None,
    quote: str | None = None,
    evidence_ids: Sequence[str] | None = None,
    inference: bool = False,
) -> CitationCheck:
    passage = passages.get(source_id)
    check = CitationCheck(
        ref=ref, source_id=source_id, known=passage is not None, statement=statement, quote=quote
    )
    if passage is None:
        check.notes.append("Source ID was not provided to the model (fabricated or invalid).")
        if quote is not None:
            check.quote_status = "not_found"
        return check
    check.doc_id, check.filename, check.page_number = (
        passage.doc_id,
        passage.filename,
        passage.page_number,
    )
    if quote is not None:
        check.quote_status, check.quote_similarity = match_quote(quote, passage.text)
        if check.quote_status == "not_found":
            check.notes.append("Quoted text was not found in the cited passage.")
    if statement:
        ids = [i for i in (evidence_ids or [source_id]) if i in passages]
        score, missing = support_score(
            statement, (passages[i].text for i in ids), inference=inference
        )
        check.support_score, check.support_label = score, _label(score)
        if missing:
            check.notes.append("Numbers not found in the cited passage(s): " + ", ".join(missing))
    return check


def _passage_map(passages: Sequence[SourcePassage]) -> dict[str, SourcePassage]:
    return {p.source_id: p for p in passages}


def _scan_canary(report: GroundingReport, texts: Iterable[str]) -> None:
    if any(PROMPT_CANARY.lower() in (t or "").lower() for t in texts):
        report.canary_leak = True
        report.warnings.append(
            "The output contains the internal prompt reference: possible prompt disclosure."
        )


def _record_unknown(
    report: GroundingReport, ids: Iterable[str], passages: dict[str, SourcePassage]
) -> None:
    for sid in ids:
        if sid not in passages and sid not in report.unknown_source_ids:
            report.unknown_source_ids.append(sid)


# --------------------------------------------------------------------------- task validators


def validate_qa(output: QAOutput, passages: Sequence[SourcePassage]) -> GroundingReport:
    pmap = _passage_map(passages)
    report = GroundingReport(abstained=output.status == "insufficient_evidence")
    cited_ids: list[str] = []
    for ci, claim in enumerate(output.claims):
        ids = [c.source_id for c in claim.citations]
        cited_ids.extend(ids)
        if not any(i in pmap for i in ids):
            report.uncited_items.append(claim.statement)
        for qi, citation in enumerate(claim.citations):
            report.checks.append(
                _check(
                    f"claims[{ci}].citations[{qi}]",
                    citation.source_id,
                    pmap,
                    statement=claim.statement,
                    quote=citation.quote,
                    evidence_ids=ids,
                    inference=claim.claim_type == "inference",
                )
            )
    inline = extract_inline_ids(output.answer)
    _record_unknown(report, [*cited_ids, *inline], pmap)
    for conflict in output.conflicts:
        _record_unknown(report, conflict.source_ids, pmap)

    if output.status in {"answered", "partially_answered", "conflicting_evidence"}:
        if not output.claims:
            report.warnings.append(
                "The answer has no structured claims with citations; treat it as unsupported."
            )
        elif not inline:
            report.warnings.append("The answer text contains no inline [S#] citations.")
        provided = " ".join(p.text for p in passages)
        report.unsupported_numbers = sorted(_numbers(output.answer) - _numbers(provided))
        if report.unsupported_numbers:
            report.warnings.append(
                "Figures in the answer that do not appear in any provided source: "
                + ", ".join(report.unsupported_numbers)
            )
    if output.status == "conflicting_evidence" and not output.conflicts:
        report.warnings.append("Status is 'conflicting evidence' but no conflict was described.")
    if output.conflicts and output.status not in {
        "conflicting_evidence",
        "partially_answered",
        "answered",
    }:
        report.warnings.append(
            "Conflicts were reported although the answer status does not reflect them."
        )
    if report.abstained and output.claims:
        report.warnings.append("The model reported insufficient evidence but still made claims.")
    _scan_canary(report, [output.answer, *(c.statement for c in output.claims)])
    return report


def validate_summary(output: SummaryOutput, passages: Sequence[SourcePassage]) -> GroundingReport:
    pmap = _passage_map(passages)
    report = GroundingReport()
    _record_unknown(
        report,
        [
            *extract_inline_ids(output.executive_summary),
            *extract_inline_ids(output.detailed_summary),
        ],
        pmap,
    )
    groups = {
        "key_findings": output.key_findings,
        "action_items": output.action_items,
        "obligations": output.obligations,
        "risks_and_concerns": output.risks_and_concerns,
    }
    for name, points in groups.items():
        for i, point in enumerate(points):
            if not any(s in pmap for s in point.source_ids):
                report.uncited_items.append(f"{name}: {point.text}")
            _record_unknown(report, point.source_ids, pmap)
            for sid in point.source_ids:
                report.checks.append(
                    _check(
                        f"{name}[{i}]",
                        sid,
                        pmap,
                        statement=point.text,
                        evidence_ids=point.source_ids,
                    )
                )
    for i, item in enumerate(output.important_dates):
        _record_unknown(report, item.source_ids, pmap)
        for sid in item.source_ids:
            # The date itself should appear verbatim in the cited passage.
            report.checks.append(
                _check(
                    f"important_dates[{i}]", sid, pmap, statement=item.description, quote=item.date
                )
            )
    if not extract_inline_ids(output.executive_summary):
        report.warnings.append("The executive summary has no inline citations.")
    _scan_canary(report, [output.executive_summary, output.detailed_summary])
    return report


def validate_extraction(
    output: ExtractionOutput, passages: Sequence[SourcePassage]
) -> GroundingReport:
    pmap = _passage_map(passages)
    report = GroundingReport()
    for category in ExtractionOutput.model_fields:
        if category == "not_found":
            continue
        for i, item in enumerate(getattr(output, category)):
            check = _check(f"{category}[{i}]", item.source_id, pmap, quote=item.quote)
            if check.known:
                in_quote = normalize_for_match(item.value) in normalize_for_match(item.quote)
                in_passage = normalize_for_match(item.value) in normalize_for_match(
                    pmap[item.source_id].text
                )
                check.statement = item.value
                if in_passage:
                    check.support_score, check.support_label = 1.0, "likely_supported"
                else:
                    score, _ = support_score(item.value, [pmap[item.source_id].text])
                    check.support_score, check.support_label = score, _label(score)
                    check.notes.append(
                        "The extracted value does not appear verbatim in the cited passage."
                    )
                if not in_quote and in_passage:
                    check.notes.append(
                        "Value found in the passage but not inside the quoted excerpt."
                    )
            _record_unknown(report, [item.source_id], pmap)
            report.checks.append(check)
    _scan_canary(
        report,
        [
            i.value
            for c in ExtractionOutput.model_fields
            if c != "not_found"
            for i in getattr(output, c)
        ],
    )
    return report


def validate_comparison(
    output: ComparisonOutput, passages: Sequence[SourcePassage]
) -> GroundingReport:
    pmap = _passage_map(passages)
    report = GroundingReport()
    docs_in_scope = {p.doc_id for p in passages}
    for i, finding in enumerate(output.findings):
        ids = list(dict.fromkeys([*finding.source_ids, *extract_inline_ids(finding.description)]))
        _record_unknown(report, ids, pmap)
        known = [s for s in ids if s in pmap]
        if not known:
            report.uncited_items.append(f"{finding.category}: {finding.topic}")
        cited_docs = {pmap[s].doc_id for s in known}
        if (
            finding.category in CROSS_DOCUMENT_CATEGORIES
            and len(docs_in_scope) > 1
            and len(cited_docs) < 2
        ):
            report.warnings.append(
                f"Finding '{finding.topic}' ({finding.category}) cites only one document; "
                "a cross-document claim should cite both."
            )
        for sid in ids:
            report.checks.append(
                _check(
                    f"findings[{i}]",
                    sid,
                    pmap,
                    statement=finding.description,
                    evidence_ids=known,
                    inference=True,
                )
            )
    _scan_canary(report, [output.overview, *(f.description for f in output.findings)])
    return report
